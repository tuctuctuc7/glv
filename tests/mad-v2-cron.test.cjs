'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {environment,request}=require('./helpers/mad-independent-fixture.cjs');
const runtime=require('../lib/glv-mad-v2-isolated.cjs'),v2=require('../lib/glv-mad-v2.cjs');
test('actual V2 cron executes two independent passes and late completes TGLV with zero TUC Graph calls or publication changes',async()=>environment(async h=>{
 const RealDate=Date;let clock='2026-11-15T05:00:00Z';
 global.Date=class extends RealDate{constructor(...args){super(...(args.length?args:[clock]));}static now(){return +new RealDate(clock);}};
 const cron=require('../api/glv-meta-ads-v2/cron.js'),api=require('../api/glv-meta-ads-v2/fb-data.js');
 const invoke=mode=>request(cron,{mode},{authorization:'Bearer test'});
 const read=account=>request(api,{type:'daily',date_preset:'last_7d',currency:'CZK',account});
 try{
  assert.equal((await request(cron,{mode:'morning'},{})).code,401);
  const morning=await invoke('morning');assert.equal(morning.code,200,JSON.stringify(morning.body));assert.equal(morning.body.verified,true);
  assert.equal(morning.body.through,'2026-11-14');
  assert.ok(h.calls.some(([kind,p])=>kind==='GRAPH'&&p.includes(v2.ACCOUNTS[0].id)));
  const before=await read('TUC'),partial=await read('TGLV');
  assert.equal(before.code,200);assert.equal(before.body.coverage_complete,true);
  assert.equal(partial.code,200);assert.equal(partial.body.coverage_complete,false);
  assert.equal(partial.body.account_coverage.find(c=>c.account_id===v2.ACCOUNTS[1].id).complete_through,'2026-11-13');
  const tuc=await runtime.readValue(h.redis)(runtime.accountKey(v2.ACCOUNTS[0].id,'last_7d'));
  const tucBytes=new Map([...h.store].filter(([k])=>k.includes(v2.ACCOUNTS[0].id)&&k.startsWith(runtime.PREFIX)));
  h.calls.length=0;clock='2026-11-15T12:00:00Z';
  const late=await invoke('late');assert.equal(late.code,200,JSON.stringify(late.body));assert.equal(late.body.verified,true);assert.equal(late.body.through,'2026-11-14');
  const graph=h.calls.filter(([kind])=>kind==='GRAPH');assert.ok(graph.length>0);
  assert.ok(graph.every(([,p])=>!p.includes(v2.ACCOUNTS[0].id)),JSON.stringify(graph));
  assert.ok(graph.some(([,p])=>p.includes(v2.ACCOUNTS[1].id)));
  assert.ok(!h.calls.some(([cmd,k])=>cmd==='SET'&&k.includes(v2.ACCOUNTS[0].id)));
  for(const [key,bytes] of tucBytes)assert.equal(h.store.get(key),bytes,key);
  assert.deepEqual(await runtime.readValue(h.redis)(runtime.accountKey(v2.ACCOUNTS[0].id,'last_7d')),tuc);
  const after=await read('TUC'),complete=await read('TGLV');
  assert.equal(after.code,200);assert.deepEqual(after.body.rows,before.body.rows);
  assert.deepEqual(after.body.account_coverage.find(c=>c.account_id===v2.ACCOUNTS[0].id),before.body.account_coverage.find(c=>c.account_id===v2.ACCOUNTS[0].id));
  assert.equal(complete.code,200);assert.equal(complete.body.coverage_complete,true);
  assert.equal(complete.body.account_coverage.find(c=>c.account_id===v2.ACCOUNTS[1].id).complete_through,'2026-11-14');
  for(const preset of runtime.PRESETS)assert.ok(await runtime.readPreset(h.redis,preset));
  assert.ok(![...h.store.keys()].some(k=>k.startsWith('glv:published:')||k.startsWith('glv:mad:shared:')));
  h.calls.length=0;assert.equal((await invoke('late')).code,200);
  assert.equal(h.calls.filter(([kind])=>kind==='GRAPH').length,0,'verified same-pass pieces are reused');
 }finally{global.Date=RealDate;}
}));
